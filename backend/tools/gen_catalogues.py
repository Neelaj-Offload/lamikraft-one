"""Generate the frozen permission and event catalogues from docs/architecture/*.md.

Run: ``uv run python tools/gen_catalogues.py`` (from backend/). Writes
``app/platform/authz/catalogue_data.py`` and ``app/platform/events/catalogue_data.py``. The contract tests
re-parse the docs and fail if the generated data drifts, so docs and code cannot disagree.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
DOCS = BACKEND.parent / "docs" / "architecture"

TEMPLATES = {
    "emp": "employee", "mgt": "management", "sal": "sales", "ops": "operations", "fin": "finance",
    "prd": "production", "pro": "procurement", "whs": "warehouse", "cat": "catalogue",
}
SCOPE_LETTERS = {"O": "OWN", "T": "TEAM", "B": "BRANCH", "C": "COMPANY"}


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _split_top(text: str) -> list[str]:
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def parse_permissions(md: str) -> list[dict]:
    rows = []
    for line in md.splitlines():
        if not line.startswith("| `") or line.count("|") < 7:
            continue
        cells = _cells(line)
        key = cells[0].strip("`")
        if not re.fullmatch(r"[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*", key):
            continue
        scopes_cell, flags_cell, legacy_cell, slice_cell, tpl_cell = cells[1:6]
        if scopes_cell == "R":
            scopes = ["OWN", "TEAM", "BRANCH", "COMPANY"]
        else:
            scopes = [SCOPE_LETTERS[s] for s in scopes_cell.split()]
        order = ["OWN", "TEAM", "BRANCH", "COMPANY"]
        max_scope = max(scopes, key=order.index)
        flags = set(flags_cell.split())
        legacy = [re.sub(r"\s*\(.*\)", "", t).strip() for t in _split_top(legacy_cell)] if legacy_cell else []
        slice_no = int(re.match(r"(\d+)", slice_cell).group(1)) if re.match(r"(\d+)", slice_cell) else 1
        grants: dict[str, str] = {}
        if tpl_cell and tpl_cell not in {"—", "-"}:
            for token in _split_top(tpl_cell):
                words = re.sub(r"\(.*?\)", "", token).split()
                if not words or words[0] not in TEMPLATES:
                    continue
                scope = SCOPE_LETTERS.get(words[1]) if len(words) > 1 and words[1] in SCOPE_LETTERS else max_scope
                if scope not in scopes:
                    scope = max_scope
                grants[TEMPLATES[words[0]]] = scope
        rows.append(
            {
                "key": key, "scopes": scopes, "delegable": "D" in flags, "mfa": "MFA" in flags, "ra": "RA" in flags,
                "fg": "FG" in flags, "sensitive": "S" in flags, "legacy": [x for x in legacy if x], "slice": slice_no,
                "grants": grants,
            }
        )
    return rows


def _expand_names(cell: str) -> list[str]:
    names, base = [], None
    for part in [p.strip() for p in cell.split("/")]:
        part = part.strip("`").strip()
        if part.startswith("."):
            if base is None:
                continue
            names.append(base.rsplit(".", 1)[0] + part)
        else:
            names.append(part)
            base = part
    return [n for n in names if re.fullmatch(r"[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*", n)]


def _fields(cell: str) -> list[str]:
    out = []
    for token in _split_top(cell):
        token = re.sub(r"\(.*?\)", "", token)
        token = re.sub(r"\[.*?\]", "", token)
        token = re.sub(r"\{.*?\}", "", token).strip()
        for piece in token.split(" or "):
            piece = piece.strip().strip("`")
            if re.fullmatch(r"[a-z][a-z0-9_]*", piece):
                out.append(piece)
    return out


def parse_events(md: str) -> list[dict]:
    events: dict[str, dict] = {}
    for line in md.splitlines():
        if not line.startswith("| `") or line.count("|") < 6:
            continue
        cells = _cells(line)
        names = _expand_names(cells[0])
        if not names or not re.fullmatch(r"\d+", cells[1].strip()):
            continue
        version = int(cells[1])
        slice_no = int(re.match(r"(\d+)", cells[2]).group(1)) if re.match(r"(\d+)", cells[2]) else 1
        fields = _fields(cells[3])
        for name in names:
            events[name] = {"name": name, "version": version, "slice": slice_no, "fields": fields}
    return list(events.values())


def render_permissions(rows: list[dict]) -> str:
    lines = [
        '"""GENERATED by tools/gen_catalogues.py from docs/architecture/permissions.md — do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "PERMISSIONS: tuple[dict, ...] = (",
    ]
    for r in rows:
        lines.append(f"    {r!r},")
    lines += [")", ""]
    return "\n".join(lines)


def render_events(rows: list[dict]) -> str:
    lines = [
        '"""GENERATED by tools/gen_catalogues.py from docs/architecture/events.md — do not edit."""',
        "",
        "from __future__ import annotations",
        "",
        "EVENTS: tuple[dict, ...] = (",
    ]
    for r in rows:
        lines.append(f"    {r!r},")
    lines += [")", ""]
    return "\n".join(lines)


def main() -> int:
    perms = parse_permissions((DOCS / "permissions.md").read_text(encoding="utf-8"))
    events = parse_events((DOCS / "events.md").read_text(encoding="utf-8"))
    (BACKEND / "app/platform/authz/catalogue_data.py").write_text(render_permissions(perms), encoding="utf-8", newline="\n")
    (BACKEND / "app/platform/events/catalogue_data.py").write_text(render_events(events), encoding="utf-8", newline="\n")
    print(f"permissions: {len(perms)}  events: {len(events)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
